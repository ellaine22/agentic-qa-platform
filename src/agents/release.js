// Release agent: produces the go/no-go recommendation and the release dashboard.
// The recommendation is a rule, not a judgement call, so it can be argued with.

import { confluence } from '../connectors/index.js';
import { getCaseFile, advance, openGate, isApproved, logEvent } from '../orchestrator/store.js';

const RULES = [
  {
    id: 'no-open-high-bugs',
    describe: 'No open high-severity bug',
    check: ({ bugs }) => bugs.filter(b => b.severity === 'high' && b.status !== 'closed').length === 0,
    explain: ({ bugs }) => `${bugs.filter(b => b.severity === 'high' && b.status !== 'closed').length} open high-severity bug(s)`
  },
  {
    id: 'p1-passed',
    describe: 'Every P1 case passed in every treatment',
    check: ({ p1 }) => p1.every(r => r.verdict === 'pass' || r.humanReview?.verdict === 'pass'),
    explain: ({ p1 }) => `${p1.filter(r => !(r.verdict === 'pass' || r.humanReview?.verdict === 'pass')).length} P1 case result(s) not passing`
  },
  {
    id: 'review-complete',
    describe: 'Every verdict needing review has been reviewed',
    check: ({ results }) => results.filter(r => r.verdict === 'needs-review' && !r.humanReview).length === 0,
    explain: ({ results }) => `${results.filter(r => r.verdict === 'needs-review' && !r.humanReview).length} verdict(s) still unreviewed`
  },
  {
    id: 'execution-gate',
    describe: 'Execution review gate approved',
    check: ({ executionApproved }) => executionApproved,
    explain: () => 'execution_review gate not approved'
  },
  {
    id: 'evidence-present',
    describe: 'Every pass carries evidence',
    check: ({ results }) => results.filter(r => r.verdict === 'pass' && !r.evidence?.length).length === 0,
    explain: ({ results }) => `${results.filter(r => r.verdict === 'pass' && !r.evidence?.length).length} pass(es) without evidence`
  }
];

export async function run(db, key, { testcases }) {
  const cf = getCaseFile(db, key);
  const run = db.runs.filter(r => r.key === key).at(-1);
  if (!run) throw new Error(`No run for ${key} yet`);

  const all = testcases.all();
  const results = run.results;
  const p1 = results.filter(r => (all.find(c => c.id === r.caseId)?.priority ?? 'P2') === 'P1');
  const bugs = db.bugs.filter(b => b.key === key);
  const ctx = { results, p1, bugs, executionApproved: isApproved(db, key, 'execution_review') };

  const checks = RULES.map(rule => {
    const ok = rule.check(ctx);
    return { id: rule.id, describe: rule.describe, ok, detail: ok ? null : rule.explain(ctx) };
  });

  const blocking = checks.filter(c => !c.ok);
  const recommendation = blocking.length === 0 ? 'go' : 'no-go';

  // Treatment comparison, which is what makes the flag decision possible.
  const byTreatment = {};
  for (const r of results) {
    const t = r.treatment ?? 'default';
    byTreatment[t] ??= { total: 0, pass: 0, fail: 0, needsReview: 0 };
    byTreatment[t].total += 1;
    if (r.verdict === 'pass') byTreatment[t].pass += 1;
    if (r.verdict === 'fail') byTreatment[t].fail += 1;
    if (r.verdict === 'needs-review') byTreatment[t].needsReview += 1;
  }

  const body = [
    `**Recommendation: ${recommendation.toUpperCase()}**`,
    '',
    `Run \`${run.id}\` · driver \`${run.driver}\` · autonomy level ${run.autonomyLevel} · flag \`${cf.flag ?? 'none'}\``,
    '',
    '## Checks',
    '',
    '| Check | Result | Detail |',
    '|---|---|---|',
    ...checks.map(c => `| ${c.describe} | ${c.ok ? 'pass' : 'blocked'} | ${c.detail ?? ''} |`),
    '',
    '## By treatment',
    '',
    '| Treatment | Cases | Pass | Fail | Needs review |',
    '|---|---|---|---|---|',
    ...Object.entries(byTreatment).map(([t, s]) => `| ${t} | ${s.total} | ${s.pass} | ${s.fail} | ${s.needsReview} |`),
    '',
    '## Open bugs',
    '',
    bugs.length
      ? bugs.map(b => `- **${b.id}** (${b.severity}) ${b.summary} — cases ${b.caseIds.join(', ')}`).join('\n')
      : '- None',
    '',
    '---',
    '',
    'Generated by the release agent. A GO recommendation is still subject to the release_signoff gate.'
  ].join('\n');

  const page = confluence.publish(`RELEASE-${key}`, `Release dashboard: ${key}`, body);

  cf.decisions.release = { recommendation, checks, byTreatment, page: page.url, at: new Date().toISOString() };
  advance(db, key, 'release-candidate');
  logEvent(db, { actor: 'release', action: 'recommendation', subject: key, detail: recommendation });

  const gate = openGate(db, {
    key,
    type: 'release_signoff',
    role: 'qa-lead',
    summary: `Release sign-off for ${key}. Agent recommends ${recommendation.toUpperCase()}${blocking.length ? `: ${blocking.map(b => b.detail).join('; ')}` : ''}`,
    payload: { recommendation, blocking: blocking.map(b => b.id), page: page.url }
  });

  return { recommendation, checks, byTreatment, page, gate };
}
