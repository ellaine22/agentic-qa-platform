// Automation agent: turns executed cases into tagged Cypress specs and Maestro
// flows, and promotes the winning treatment once an experiment concludes.
//
// Codegen is deterministic and template driven. Steps it recognises become real
// commands; steps it does not recognise become an explicit TODO with the step
// text, never a guessed selector. A spec that quietly asserts nothing is worse
// than one that fails review.

import { testcases, git, flags } from '../connectors/index.js';
import { getCaseFile, logEvent } from '../orchestrator/store.js';

const WEB_PATTERNS = [
  { match: /sign in|log in|open the sign-in/i, emit: () => `    cy.signIn();` },
  { match: /add .*to the cart/i, emit: () => `    cy.get('[data-test^=add-to-cart]').first().click();` },
  { match: /open the cart|proceed to/i, emit: () => `    cy.get('.shopping_cart_link').click();` },
  { match: /start checkout|begin checkout/i, emit: () => `    cy.get('[data-test=checkout]').click();` },
  { match: /enter .*first name|customer details|delivery details/i, emit: () => `    cy.fillCheckoutForm({ firstName: 'Ada', lastName: 'Lovelace', postalCode: 'N2H 1A1' });` },
  { match: /continue/i, emit: () => `    cy.get('[data-test=continue]').click();` },
  { match: /finish|place the order|complete/i, emit: () => `    cy.get('[data-test=finish]').click();` },
  { match: /cancel/i, emit: () => `    cy.get('[data-test=cancel]').click();` },
  { match: /sort/i, emit: () => `    cy.get('[data-test=product-sort-container]').select('lohi');` },
  { match: /remove/i, emit: () => `    cy.get('[data-test^=remove]').first().click();` }
];

const WEB_ASSERTIONS = [
  { match: /catalog page loads|catalog is shown|products are listed/i, emit: () => `    cy.url().should('include', '/inventory.html');\n    cy.get('.inventory_item').should('have.length.at.least', 1);` },
  { match: /cart badge shows one|badge shows/i, emit: () => `    cy.get('.shopping_cart_badge').should('have.text', '1');` },
  { match: /badge is no longer|cart badge is cleared|empty cart/i, emit: () => `    cy.get('.shopping_cart_badge').should('not.exist');` },
  { match: /confirmation/i, emit: () => `    cy.get('.complete-header').should('be.visible');` },
  { match: /error/i, emit: () => `    cy.get('[data-test=error]').should('be.visible');` },
  { match: /own image|no two items share an image/i, emit: () => `    cy.get('.inventory_item_img img').then(($imgs) => {\n      const sources = [...$imgs].map((img) => img.getAttribute('src'));\n      expect(new Set(sources).size, 'each item has its own image').to.equal(sources.length);\n    });` },
  { match: /ascending/i, emit: () => `    cy.get('.inventory_item_price').then(($p) => {\n      const prices = [...$p].map((el) => Number(el.innerText.replace('$', '')));\n      expect(prices).to.deep.equal([...prices].sort((a, b) => a - b));\n    });` },
  { match: /tax is 8%|tax and the total/i, emit: () => `    cy.get('.summary_subtotal_label').invoke('text').then((subtotal) => {\n      const items = Number(subtotal.replace(/[^0-9.]/g, ''));\n      cy.get('.summary_tax_label').invoke('text').then((taxText) => {\n        const tax = Number(taxText.replace(/[^0-9.]/g, ''));\n        expect(tax).to.be.closeTo(items * 0.08, 0.01);\n      });\n    });` }
];

// A step whose action maps to no known command, or whose expectation maps to no
// known assertion, becomes an explicit TODO carrying the original text. The
// coverage agent treats any spec block containing a TODO as a draft, not as
// automation, so an unfinished spec never inflates the coverage number.
function emitStep(step) {
  const lines = [];
  // A "Verify:" step carries no action, only the thing to assert.
  if (!/^verify:/i.test(step.action)) {
    const action = WEB_PATTERNS.find(p => p.match.test(step.action));
    lines.push(action ? action.emit(step) : `    // TODO map this action: ${step.action}${step.target ? ` (hint: ${step.target})` : ''}`);
  }
  if (step.expect) {
    const assertion = WEB_ASSERTIONS.find(p => p.match.test(step.expect));
    lines.push(assertion ? assertion.emit(step) : `    // TODO write this assertion: ${step.expect}`);
  }
  return lines.join('\n');
}

function cypressSpec({ title, cases, flagKey, treatment }) {
  const header = [
    '// Generated by the automation agent from executed test cases.',
    '// Each test carries its case ID as @case:<ID>. The coverage agent reads these',
    '// tags, so renaming a test without its tag silently drops coverage.',
    treatment ? `// Flag: ${flagKey} · treatment: ${treatment}` : '',
    '',
    `describe('${title}', () => {`,
    treatment ? `  beforeEach(() => {\n    cy.setTreatment('${flagKey}', '${treatment}');\n  });\n` : ''
  ].filter(Boolean).join('\n');

  const body = cases.map(c => {
    const steps = (c.steps ?? []).map(emitStep).join('\n');
    const evidence = c.evidenceRequired ? `\n    cy.evidence('${c.id}');` : '';
    return `  it('@case:${c.id} ${c.title.replace(/'/g, "\\'")}', () => {\n${steps}${evidence}\n  });`;
  }).join('\n\n');

  return `${header}\n${body}\n});\n`;
}

function maestroFlow(c) {
  const steps = (c.steps ?? []).map(s =>
    `  # ${s.action}\n  - assertVisible: "${(s.target ?? s.expect).replace(/"/g, '')}"`
  ).join('\n');
  return `# @case:${c.id} ${c.title}\n# Generated by the automation agent.\nappId: \${APP_ID}\nenv:\n  TREATMENT: \${TREATMENT}\n---\n- launchApp\n${steps}\n`;
}

export function generate(db, key, { platform = 'web' } = {}) {
  const cf = getCaseFile(db, key);
  const all = testcases.all();
  const projectCases = cf.cases.map(id => all.find(c => c.id === id)).filter(Boolean).filter(c => c.platform === platform);
  if (!projectCases.length) throw new Error(`No ${platform} project cases to automate for ${key}`);

  const written = [];

  if (platform === 'web') {
    const byTreatment = {};
    for (const c of projectCases) (byTreatment[c.treatment ?? 'default'] ??= []).push(c);
    for (const [treatment, cases] of Object.entries(byTreatment)) {
      const file = `cypress/e2e/web/${key.toLowerCase()}-${treatment}.cy.js`;
      git.writeSpec(file, cypressSpec({
        title: `${key} ${treatment === 'default' ? '' : treatment}`.trim(),
        cases,
        flagKey: cf.flag,
        treatment: treatment === 'default' ? null : treatment
      }));
      written.push({ file, treatment, cases: cases.map(c => c.id) });
    }
  } else {
    for (const c of projectCases) {
      const file = `maestro/flows/${c.id.toLowerCase()}.yaml`;
      git.writeSpec(file, maestroFlow(c));
      written.push({ file, treatment: c.treatment, cases: [c.id] });
    }
  }

  logEvent(db, { actor: 'automation', action: 'specs-generated', subject: key, detail: written.map(w => w.file).join(', ') });
  return { written, note: 'Specs are raised as a PR for engineer review. Any TODO marker in a generated spec blocks merge.' };
}

// Promote the winning treatment: keep its specs, delete the loser's, drop the
// flag from the flag platform.
export function promote(db, flagKey, winner) {
  const flag = flags.get(flagKey);
  const losing = flag.treatments.map(t => t.key).filter(t => t !== winner);

  const removed = [];
  const kept = [];
  for (const spec of git.specs()) {
    const m = spec.path.match(/-([a-z0-9]+)\.cy\.js$/);
    if (!m) continue;
    if (!spec.text.includes(flagKey)) continue;
    if (losing.includes(m[1])) { git.removeSpec(spec.path); removed.push(spec.path); }
    else if (m[1] === winner) {
      // Strip the treatment override: at 100% there is no flag to set.
      const cleaned = spec.text
        .replace(/\n\s*beforeEach\(\(\) => \{\n\s*cy\.setTreatment\([^)]*\);\n\s*\}\);\n/, '\n')
        .replace(new RegExp(`^// Flag: ${flagKey}.*$\\n`, 'm'), '');
      git.writeSpec(spec.path, cleaned);
      kept.push(spec.path);
    }
  }

  const all = flags.all();
  const target = all.find(f => f.key === flagKey);
  target.status = 'launched';
  target.experiment.winner = winner;
  target.experiment.status = 'concluded';
  for (const env of Object.values(target.environments)) {
    env.defaultTreatment = winner;
    env.allocation = { [winner]: 100 };
  }
  flags.write(all);

  logEvent(db, { actor: 'automation', action: 'promote', subject: flagKey, detail: `winner ${winner}, removed ${removed.length} spec(s)` });
  return { winner, kept, removed, flagCleanup: `Flag ${flagKey} set to 100% ${winner}; remove the flag check from application code next.` };
}
