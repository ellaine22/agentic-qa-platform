// Planner agent: epic + stories + Confluence docs -> test plan, published to
// Confluence, then a plan_approval gate for the QA lead.

import { jira, confluence, flags } from '../connectors/index.js';
import { complete } from '../llm/index.js';
import { createCaseFile, getCaseFile, advance, openGate, logEvent } from '../orchestrator/store.js';

export async function run(db, key) {
  const epic = jira.getEpic(key);
  const docs = (epic.confluence ?? []).map(id => confluence.getPage(id)).filter(Boolean);
  const flag = epic.flag ? flags.get(epic.flag) : null;

  const cf = createCaseFile(db, { key, epic: epic.key, flag: epic.flag, platforms: epic.platforms });

  const plan = await complete({ task: 'test-plan', context: { epic, docs, flag } });

  const body = plan.sections.map(s => `## ${s.heading}\n\n${s.body}`).join('\n\n') +
    `\n\n---\n\nSources: ${plan.sources.join(', ')}\n\nGenerated by the planner agent (${plan._meta.provider} provider). Not approved until the plan_approval gate is signed.`;

  const page = confluence.publish(`TESTPLAN-${key}`, plan.title, body);

  cf.plan = { title: plan.title, page: page.url, sections: plan.sections.length, sources: plan.sources, generatedAt: new Date().toISOString() };
  advance(db, key, 'planning');
  logEvent(db, { actor: 'planner', action: 'plan-generated', subject: key, detail: page.url });

  const gate = openGate(db, {
    key,
    type: 'plan_approval',
    role: 'qa-lead',
    summary: `Approve the test plan for ${key}: ${plan.title}`,
    payload: { page: page.url, sections: plan.sections.map(s => s.heading) }
  });

  return { page, gate, plan };
}
